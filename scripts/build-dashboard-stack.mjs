#!/usr/bin/env node
/**
 * Synthesize the CloudFormation template for the Productboard-MCP usage dashboard.
 *
 * The dashboard body stays plain, editable JSON in
 * `infra/cloudwatch-usage-dashboard.json` (the single source of truth). This
 * script wraps that body into an `AWS::CloudWatch::Dashboard` resource and
 * writes `infra/cloudwatch-usage-dashboard.cfn.json`, so the dashboard is
 * managed as a declarative, drift-detectable CloudFormation stack instead of a
 * manual `aws cloudwatch put-dashboard`.
 *
 * Workflow:
 *   1. Edit infra/cloudwatch-usage-dashboard.json
 *   2. node scripts/build-dashboard-stack.mjs            # regenerate the template
 *   3. aws cloudformation deploy \
 *        --stack-name productboard-mcp-dashboard \
 *        --template-file infra/cloudwatch-usage-dashboard.cfn.json \
 *        --region us-east-1
 *
 * Or, for an ad-hoc push without CloudFormation:
 *   aws cloudwatch put-dashboard \
 *     --dashboard-name Productboard-MCP-Usage-Monitoring \
 *     --region us-east-1 \
 *     --dashboard-body file://infra/cloudwatch-usage-dashboard.json
 *
 * Mirrors the gsuite-mcp infra/ pattern so both services manage their
 * dashboards identically.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'infra', 'cloudwatch-usage-dashboard.json');
const OUT = path.join(ROOT, 'infra', 'cloudwatch-usage-dashboard.cfn.json');
const DASHBOARD_NAME = 'Productboard-MCP-Usage-Monitoring';

const bodyText = readFileSync(SRC, 'utf8');

// Validate the source is well-formed before embedding — a malformed body would
// otherwise fail opaquely at deploy time inside CloudFormation.
let parsed;
try {
  parsed = JSON.parse(bodyText);
} catch (e) {
  console.error(`infra/cloudwatch-usage-dashboard.json is not valid JSON: ${e.message}`);
  process.exit(1);
}
if (!parsed || !Array.isArray(parsed.widgets)) {
  console.error('dashboard JSON has no `widgets` array — refusing to build.');
  process.exit(1);
}

const template = {
  AWSTemplateFormatVersion: '2010-09-09',
  Description:
    'Productboard MCP usage-monitoring CloudWatch dashboard. Source of truth: ' +
    'infra/cloudwatch-usage-dashboard.json. Regenerate with ' +
    'scripts/build-dashboard-stack.mjs; do not edit this file by hand.',
  Resources: {
    UsageDashboard: {
      Type: 'AWS::CloudWatch::Dashboard',
      Properties: {
        DashboardName: DASHBOARD_NAME,
        // Embed the source body as a compact JSON string (what PutDashboard expects).
        DashboardBody: JSON.stringify(parsed),
      },
    },
  },
  Outputs: {
    DashboardName: { Value: DASHBOARD_NAME },
    DashboardURL: {
      Value:
        'https://us-east-1.console.aws.amazon.com/cloudwatch/home?region=us-east-1#dashboards/dashboard/' +
        DASHBOARD_NAME,
    },
  },
};

writeFileSync(OUT, JSON.stringify(template, null, 2) + '\n');
console.log(
  `Wrote ${path.relative(ROOT, OUT)} — ${parsed.widgets.length} widgets, body ${bodyText.length} bytes.`,
);
console.log(
  'Deploy: aws cloudformation deploy --stack-name productboard-mcp-dashboard ' +
    '--template-file infra/cloudwatch-usage-dashboard.cfn.json --region us-east-1',
);
